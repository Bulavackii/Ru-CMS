      // resize) иначе дают три пересчёта на одно движение.
      function отложить() {
        if (ждём) return;
        ждём = true;
        requestAnimationFrame(function () { ждём = false; apply(); });
      }

      if (window.ResizeObserver && sb) new ResizeObserver(отложить).observe(sb);
      window.addEventListener('resize', отложить, { passive: true });
      document.addEventListener('DOMContentLoaded', apply);
    })();
  </script>

