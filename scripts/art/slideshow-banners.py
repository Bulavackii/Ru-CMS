def записать(имя, Ш, В, тело, заголовок, подпись, пояснение):
    svg = ('<?xml version="1.0" encoding="UTF-8"?>\n'
           '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d" '
           'role="img" aria-label="%s">\n'
           '  <title>%s</title>\n<!--\n%s\n-->\n<style>%s</style>\n%s\n</svg>\n'
           % (Ш, В, Ш, В, подпись, заголовок, пояснение, СТИЛИ, тело))
    данные = svg.encode('utf-8')
    open(os.path.join(ВЫХОД, имя), 'wb').write(данные)
    print('%-14s %6.1f KB  %dx%d' % (имя, len(данные) / 1024, Ш, В))


