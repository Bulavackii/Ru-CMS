"""
Слайды баннеров по умолчанию — в том же языке, что фоны тем.

Общая подложка (`подложка()`) повторяет фирменную композицию: гранёное ЯДРО,
СВЯЗИ от него, СОТЫ и ОРБИТЫ. Разница со фоном тем в двух вещах:

  • ядро смещено вправо, чтобы слева осталось место под текст;
  • подложка СВЕТЛАЯ: слайд должен читаться как большая карточка страницы,
    а не как чужой тёмный баннер посреди светлой ленты;
  • палитра фиксированная (индиго), а не по теме: слайд — это содержимое,
    он живёт в базе и не должен меняться от смены оформления.

⚠️ Шрифт только системный: проект самодостаточен, внешних обращений быть не
должно, а `<image>`/`@font-face` в SVG тянули бы файл наружу.

⚠️ Светящихся узлов нет — то же решение, что и в фонах тем.

Файлы СОБРАНЫ этим генератором (scripts/art/slideshow-banners.py).
Правят генератор и пересобирают, а не сами файлы.
"""
import math
import os
