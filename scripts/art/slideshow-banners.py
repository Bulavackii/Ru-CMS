ВЫХОД = 'modules/Slideshow/Resources/defaults'

# 🔴 У СЛАЙДА НЕТ СОБСТВЕННОГО ФОНА — его рисует CSS из переменных темы.
#
# Три захода подбирать фон вручную (почти чёрный → почти белый → насыщенный
# индиго) упирались в одно и то же: тем одиннадцать, и фон, удачный для одной,
# спорит с другой. Угадать один цвет на все — задача без решения.
#
# Поэтому фон отсюда убран вовсе: SVG прозрачный, а подложку даёт правило
# `.ru-slide` в самой вьюхе —
#     linear-gradient(color-mix(primary 50%, #0f172a), color-mix(primary 32%, #0f172a))
# то есть цвет ТЕМЫ, затемнённый до предсказуемого уровня. Меняется тема —
# меняется и слайд, ровно как у кнопок.
#
# Графика поэтому НЕЙТРАЛЬНАЯ: белая с разной прозрачностью плюс чёрная для
# теневых граней. Любой оттенок подложки она принимает как есть — своего цвета
# у неё нет, спорить не с чем.
#
# Доли смеси (50/32) подобраны не на глаз: они проверены по ВСЕМ одиннадцати
# темам, худший случай — Неон (самый светлый основной цвет). Там белый текст
# даёт 6.92, второстепенный #dbeafe — 5.67, зелёный #bbf7d0 — 5.71. Возьми
# долю больше — Неон уйдёт ниже порога.
БЕЛ, ВТОР = '#ffffff', '#dbeafe'
ЗЕЛ = '#bbf7d0'
# Псевдонимы под прежние имена в коде рисования: графика вся белая.
ОСН = АКЦ = НАШ = СВЕТ = БЕЛ
ТУСК = НАДЗАГ = ВТОР
ТЕНЬ = '#000000'


def сота(cx, cy, r):
    т = []
    for k in range(6):
        a = math.radians(60 * k - 30)
        т.append('%.1f,%.1f' % (cx + r * math.cos(a), cy + r * math.sin(a)))
    return ' '.join(т)


def подложка(Ш, В, зерно, ядроX=None, ядроУ=None, масштаб=1.0, кристалл=True):
    """Фирменная подложка слайда: ядро, связи, соты, орбиты.

    🔴 `кристалл=False` — для слайдов, где содержимое занимает ВСЮ ширину.
    Гранёное ядро — самая плотная часть рисунка, и за текстом оно читается
    как грязное пятно: владелец показал снимком, что на сравнении оно легло
    ровно на колонку «1С-Битрикс», а на шагах установки — на «Содержимое».
    Свободного места на таких слайдах нет вовсе, двигать ядро некуда,
    поэтому там остаются только сеть, соты и орбиты: они разрежены и
    тексту не мешают.
    """
    сл = random.Random(зерно)
    цх = ядроX if ядроX is not None else Ш * 0.74
    цу = ядроУ if ядроУ is not None else В * 0.5
    ч = []

    ч.append('<defs>')
    ч.append('<radialGradient id="halo" cx="50%%" cy="50%%" r="50%%">'
             '<stop offset="0" stop-color="%s" stop-opacity=".26"/>'
             '<stop offset="1" stop-color="%s" stop-opacity="0"/></radialGradient>' % (АКЦ, АКЦ))
    for имя, a, b in (('fA', БЕЛ, БЕЛ), ('fB', БЕЛ, ТЕНЬ), ('fC', ТЕНЬ, БЕЛ)):
        ч.append('<linearGradient id="%s" x1="0" y1="0" x2="1" y2="1">'
                 '<stop offset="0" stop-color="%s"/><stop offset="1" stop-color="%s"/></linearGradient>' % (имя, a, b))
    # Слева текст светлый — подложку под ним ЗАТЕМНЯЕМ до тёмного конца
    # градиента, чтобы надпись не спорила с рисунком сети.
    ч.append('<linearGradient id="shade" x1="0" y1="0" x2="1" y2="0">'
             '<stop offset="0" stop-color="%s" stop-opacity=".55"/>'
             '<stop offset=".54" stop-color="%s" stop-opacity=".28"/>'
             '<stop offset="1" stop-color="%s" stop-opacity="0"/></linearGradient>' % (ТЕНЬ, ТЕНЬ, ТЕНЬ))
    ч.append('</defs>')

    ч.append('<ellipse cx="%.0f" cy="%.0f" rx="%.0f" ry="%.0f" fill="url(#halo)"/>'
             % (цх, цу, 430 * масштаб, 330 * масштаб))

    # ── Соты вокруг ядра ──
    R = 46 * масштаб
    шагX, шагY = R * math.sqrt(3), R * 1.5
    ряд, y = 0, -R
    while y < В + R:
        x = -R + (0 if ряд % 2 == 0 else шагX / 2)
        while x < Ш + R:
            d = math.hypot((x - цх) / (500 * масштаб), (y - цу) / (330 * масштаб))
            if d < 1.0:
                оп = 0.05 + 0.22 * (1 - d)
                ч.append('<polygon points="%s" fill="none" stroke="%s" stroke-width="1" opacity="%.3f"/>'
                         % (сота(x, y, R * 0.86), ОСН, оп))
            x += шагX
        y += шагY
        ряд += 1

    # ── Орбиты ──
    for rx, ry, оп in ((250, 190, 0.16), (350, 262, 0.11), (450, 330, 0.07)):
        ч.append('<ellipse cx="%.0f" cy="%.0f" rx="%.0f" ry="%.0f" fill="none" stroke="%s" '
                 'stroke-width="1.2" opacity="%.2f"/>' % (цх, цу, rx * масштаб, ry * масштаб, ОСН, оп))

    # ── Внешние узлы и связи ──
    внешние = []
    for i in range(12):
        a = 2 * math.pi * i / 12 + сл.uniform(-0.1, 0.1)
        rr = сл.choice((250, 350, 450)) * масштаб * сл.uniform(0.94, 1.04)
        внешние.append((цх + rr * math.cos(a), цу + rr * 0.74 * math.sin(a)))
    for x, y in внешние:
        ч.append('<line x1="%.0f" y1="%.0f" x2="%.0f" y2="%.0f" stroke="%s" stroke-width="1" opacity=".16"/>'
                 % (цх, цу, x, y, ОСН))
        ч.append('<circle cx="%.0f" cy="%.0f" r="3" fill="%s" opacity=".34"/>' % (x, y, ОСН))
    for i, a in enumerate(внешние):
        b = внешние[(i + 1) % len(внешние)]
        ч.append('<line x1="%.0f" y1="%.0f" x2="%.0f" y2="%.0f" stroke="%s" stroke-width=".9" opacity=".13"/>'
                 % (a[0], a[1], b[0], b[1], АКЦ))

    # ── Гранёное ядро ──
    if not кристалл:
        # Затемнение слева всё равно нужно: текст лежит на нём.
        ч.append('<rect width="%d" height="%d" fill="url(#shade)"/>' % (Ш, В))
        return '\n'.join(ч)

    def кольцо(r, шт, фаза):
        return [(цх + r * масштаб * math.cos(2 * math.pi * i / шт + фаза),
                 цу + r * масштаб * 0.74 * math.sin(2 * math.pi * i / шт + фаза)) for i in range(шт)]

    внутр = кольцо(84, 7, сл.uniform(0, 1))
    средн = кольцо(162, 7, сл.uniform(0, 1) + math.pi / 7)
    внешн = кольцо(232, 7, сл.uniform(0, 1))
    грани = ('fA', 'fB', 'fC')

    for i in range(7):
        a, b = внутр[i], внутр[(i + 1) % 7]
        ч.append('<path d="M%.0f,%.0f L%.0f,%.0f L%.0f,%.0f Z" fill="url(#%s)" opacity="%.2f"/>'
                 % (цх, цу, a[0], a[1], b[0], b[1], грани[i % 3], 0.16 + 0.06 * (i % 3)))
    for i in range(7):
        a, b, c = внутр[i], внутр[(i + 1) % 7], средн[i]
        ч.append('<path d="M%.0f,%.0f L%.0f,%.0f L%.0f,%.0f Z" fill="url(#%s)" opacity="%.2f"/>'
                 % (a[0], a[1], b[0], b[1], c[0], c[1], грани[(i + 1) % 3], 0.11 + 0.05 * (i % 3)))
        d = средн[(i + 1) % 7]
        ч.append('<path d="M%.0f,%.0f L%.0f,%.0f L%.0f,%.0f Z" fill="url(#%s)" opacity="%.2f"/>'
                 % (b[0], b[1], c[0], c[1], d[0], d[1], грани[(i + 2) % 3], 0.07 + 0.03 * (i % 3)))
    for i in range(7):
        c, d, e = средн[i], внешн[i], средн[(i + 1) % 7]
        ч.append('<path d="M%.0f,%.0f L%.0f,%.0f L%.0f,%.0f Z" fill="url(#%s)" opacity="%.2f"/>'
                 % (c[0], c[1], d[0], d[1], e[0], e[1], грани[i % 3], 0.04 + 0.02 * (i % 2)))
    for набор, оп in ((внутр, 0.40), (средн, 0.26), (внешн, 0.13)):
        for i in range(len(набор)):
            a, b = набор[i], набор[(i + 1) % len(набор)]
            ч.append('<line x1="%.0f" y1="%.0f" x2="%.0f" y2="%.0f" stroke="%s" '
                     'stroke-width="1.1" opacity="%.2f"/>' % (a[0], a[1], b[0], b[1], ОСН, оп))
    for i in range(7):
        ч.append('<line x1="%.0f" y1="%.0f" x2="%.0f" y2="%.0f" stroke="%s" stroke-width="1" opacity=".24"/>'
                 % (цх, цу, внутр[i][0], внутр[i][1], ОСН))

    # Затемнение слева — под текст.
    ч.append('<rect width="%d" height="%d" fill="url(#shade)"/>' % (Ш, В))
    return '\n'.join(ч)


