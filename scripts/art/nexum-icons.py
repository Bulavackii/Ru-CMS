    # масштаба — это одно число, а не семьдесят правок.
    #
    # ⚠️ Преобразование масштабирует и ОБВОДКУ тоже. Поэтому в атрибут
    # пишется обводка, поделённая на увеличение: иначе «крупнее» означало бы
    # заодно и «толще», а нужно ровно наоборот.
