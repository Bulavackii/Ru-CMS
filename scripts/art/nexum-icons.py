def нарисовать(значок, обводка, торцы, точка):
    ч = []
    for ф in значок:
        вид = ф[0]
        if вид == 'l':
            ч.append('<line x1="%s" y1="%s" x2="%s" y2="%s"/>' % ф[1:])
        elif вид == 'r':
            ч.append('<rect x="%s" y="%s" width="%s" height="%s"/>' % ф[1:])
        elif вид == 'c':
            ч.append('<circle cx="%s" cy="%s" r="%s"/>' % ф[1:])
        elif вид == 'p':
            ч.append('<path d="%s"/>' % ф[1])
        elif вид == 'd':
            # Узел заливается всегда: это примета набора — связь и точка.
            ч.append('<circle cx="%s" cy="%s" r="%s" fill="currentColor" stroke="none"/>' % (ф[1], ф[2], точка))
    return '\n  '.join(ч)


