# -*- coding: utf-8 -*-
"""
Фирменные фоны тем.

Смысл рисунка — само имя продукта: **Nexum** (связь) и **Core** (ядро).
Отсюда композиция, одна на все темы:

  • гранёное ЯДРО в середине — кристалл из треугольников;
  • СВЯЗИ от ядра к внешним узлам;
  • сотовая структура вокруг — модульность системы;
  • орбитальные кольца — спокойный каркас композиции.

Это не «узор из фигурок», а знак: та же мысль, что в бейдже NC и в значке
слоёв. От темы к теме меняется только палитра и разворот композиции.

⚠️ Светящихся узлов НЕТ намеренно. Блики были главной приметой прежнего
растрового Индиго: на светлом фоне они читаются как засветка от вспышки,
спорят с текстом карточек и выдают стоковую картинку.

⚠️ Края уходят в ровный цвет фона: слой повторяется
(`background-repeat: repeat`), и только так стык не виден.

⚠️ Случайность СЕЯНАЯ: тот же вызов даёт тот же файл. Иначе каждый прогон
сидера менял бы вид сайта.

Файлы СОБРАНЫ этим генератором — руками их не правят, меняют генератор.
"""
import math
import os
import random

ВЫХОД = 'public/images/themes/backgrounds'
Ш, В = 1408, 768


# (слаг, фон, основной, акцент, тёмный, зерно, разворот°, имя)
ТЕМЫ = [
    ('indigo',   '#f8fafc', '#6366f1', '#8b5cf6', '#312e81', 10,  0, 'Индиго'),
    ('scarlet',  '#f7f8fa', '#d32b1a', '#f2542d', '#7f1508', 21, 14, 'Алый'),
    ('azure',    '#f5f8ff', '#0057e7', '#3d8bff', '#02306f', 32, -9, 'Лазурь'),
    ('graphite', '#f7f9f9', '#0f1419', '#1274c4', '#0f1419', 43, 22, 'Графит'),
    ('magenta',  '#fdf6fa', '#c2185b', '#e0407e', '#6d0d33', 54, -18, 'Пурпур'),
    ('mono',     '#ffffff', '#171717', '#525252', '#0a0a0a', 65,  7, 'Монохром'),
    ('amber',    '#fffdf7', '#b45309', '#d97706', '#5c2a03', 76, -25, 'Янтарь'),
    ('pine',     '#f6faf7', '#166534', '#15803d', '#06301a', 87, 11, 'Хвоя'),
    ('ocean',    '#f4fafb', '#0e7490', '#0891b2', '#053845', 98, -14, 'Океан'),
    ('plum',     '#faf7fc', '#6b21a8', '#7e22ce', '#33064f', 109, 19, 'Слива'),
    ('neon',     '#0b0a14', '#a78bfa', '#22d3ee', '#4c1d95', 120, -6, 'Неон'),
]

ЦХ, ЦУ = Ш / 2, В / 2


def затухание(x, y):
    """1 в середине, 0 у края — по эллипсу, вписанному в плитку."""
    dx = (x - ЦХ) / (Ш * 0.5)
    dy = (y - ЦУ) / (В * 0.5)
    return max(0.0, 1.0 - math.hypot(dx * 0.92, dy))


def повернуть(x, y, угол):
    a = math.radians(угол)
    dx, dy = x - ЦХ, y - ЦУ
    return (ЦХ + dx * math.cos(a) - dy * math.sin(a),
            ЦУ + dx * math.sin(a) + dy * math.cos(a))


def сота(cx, cy, r, угол=0):
    точки = []
    for k in range(6):
        a = math.radians(60 * k - 30 + угол)
        точки.append('%.1f,%.1f' % (cx + r * math.cos(a), cy + r * math.sin(a)))
    return ' '.join(точки)


def нарисовать(слаг, фон, основной, акцент, тёмный, зерно, разворот, имя):
    сл = random.Random(зерно)
    ч = []

    # ─────────────────────────── заготовки ───────────────────────────
    ч.append('<defs>')
    ч.append(
        '<linearGradient id="wash" x1="0" y1="0" x2="0.6" y2="1">'
        '<stop offset="0" stop-color="%s" stop-opacity=".10"/>'
        '<stop offset=".55" stop-color="%s" stop-opacity=".05"/>'
        '<stop offset="1" stop-color="%s" stop-opacity=".12"/></linearGradient>'
        % (акцент, основной, основной)
    )
    ч.append(
        '<linearGradient id="crystalA" x1="0" y1="0" x2="1" y2="1">'
        '<stop offset="0" stop-color="%s"/><stop offset="1" stop-color="%s"/></linearGradient>'
        % (тёмный, основной)
    )
    ч.append(
        '<linearGradient id="crystalB" x1="1" y1="0.2" x2="0" y2="1">'
        '<stop offset="0" stop-color="%s"/><stop offset="1" stop-color="%s"/></linearGradient>'
        % (акцент, тёмный)
    )
    ч.append(
        '<linearGradient id="crystalC" x1="0.2" y1="1" x2="1" y2="0">'
        '<stop offset="0" stop-color="%s"/><stop offset="1" stop-color="%s"/></linearGradient>'
        % (основной, акцент)
    )
    ч.append(
        '<radialGradient id="halo"><stop offset="0" stop-color="%s" stop-opacity=".22"/>'
        '<stop offset=".6" stop-color="%s" stop-opacity=".07"/>'
        '<stop offset="1" stop-color="%s" stop-opacity="0"/></radialGradient>'
        % (акцент, основной, основной)
    )
    ч.append(
        '<radialGradient id="fade" cx="50%%" cy="50%%" r="60%%">'
        '<stop offset="0" stop-color="%s" stop-opacity="0"/>'
        '<stop offset=".58" stop-color="%s" stop-opacity="0"/>'
        '<stop offset=".84" stop-color="%s" stop-opacity=".88"/>'
        '<stop offset="1" stop-color="%s" stop-opacity="1"/></radialGradient>'
        % (фон, фон, фон, фон)
    )
    ч.append('</defs>')

    ч.append('<rect width="%d" height="%d" fill="%s"/>' % (Ш, В, фон))
    ч.append('<rect width="%d" height="%d" fill="url(#wash)"/>' % (Ш, В))

    # Мягкий ореол вокруг ядра — глубина без размытия.
    ч.append('<ellipse cx="%.0f" cy="%.0f" rx="470" ry="300" fill="url(#halo)"/>' % (ЦХ, ЦУ))

    # ─────────────────── соты: модульность системы ───────────────────
    # Шестиугольная решётка вокруг ядра. Плотность падает к краю, поэтому
    # структура читается как «ядро в окружении модулей», а не как обои.
    R = 52
    шагX = R * math.sqrt(3)
    шагY = R * 1.5
    ряд = 0
    y = -R
    while y < В + R:
        сдвиг = 0 if ряд % 2 == 0 else шагX / 2
        x = -R + сдвиг
        while x < Ш + R:
            з = затухание(x, y)
            if з > 0.06:
                cx, cy = повернуть(x, y, разворот * 0.35)
                # Ближе к ядру соты плотнее и иногда залиты.
                if з > 0.62 and сл.random() < 0.30:
                    ч.append('<polygon points="%s" fill="%s" opacity="%.3f"/>'
                             % (сота(cx, cy, R * 0.86, разворот * 0.35), акцент, 0.04 + 0.10 * з))
                ч.append('<polygon points="%s" fill="none" stroke="%s" stroke-width="%.1f" opacity="%.3f"/>'
                         % (сота(cx, cy, R * 0.86, разворот * 0.35), основной,
                            0.6 + 0.5 * з, 0.05 + 0.22 * з))
            x += шагX
        y += шагY
        ряд += 1

    # ─────────────────── орбиты: каркас композиции ───────────────────
    for rx, ry, оп in ((300, 196, 0.16), (410, 268, 0.11), (530, 346, 0.07)):
        ч.append('<ellipse cx="%.0f" cy="%.0f" rx="%d" ry="%d" fill="none" stroke="%s" '
                 'stroke-width="1.2" opacity="%.2f" transform="rotate(%d %.0f %.0f)"/>'
                 % (ЦХ, ЦУ, rx, ry, основной, оп, разворот, ЦХ, ЦУ))

    # ───────────────── внешние узлы и связи с ядром ─────────────────
    # «Nexum» — связь. Линии идут ОТ ядра наружу, к узлам на орбитах.
    внешние = []
    for i in range(14):
        a = 2 * math.pi * i / 14 + сл.uniform(-0.12, 0.12)
        rr = сл.choice((300, 410, 530)) * сл.uniform(0.92, 1.05)
        x = ЦХ + rr * math.cos(a)
        y = ЦУ + rr * 0.652 * math.sin(a)
        внешние.append(повернуть(x, y, разворот))

    for x, y in внешние:
        з = затухание(x, y)
        ч.append('<line x1="%.0f" y1="%.0f" x2="%.0f" y2="%.0f" stroke="%s" '
                 'stroke-width="1" opacity="%.2f"/>' % (ЦХ, ЦУ, x, y, основной, 0.05 + 0.16 * з))
        ч.append('<circle cx="%.0f" cy="%.0f" r="%.1f" fill="%s" opacity="%.2f"/>'
                 % (x, y, 2.6 + 2.2 * з, основной, 0.14 + 0.34 * з))

    # Хорды между соседними узлами — сеть, а не звезда.
    for i, a in enumerate(внешние):
        b = внешние[(i + 1) % len(внешние)]
        з = (затухание(*a) + затухание(*b)) / 2
        ч.append('<line x1="%.0f" y1="%.0f" x2="%.0f" y2="%.0f" stroke="%s" '
                 'stroke-width=".9" opacity="%.2f"/>' % (a[0], a[1], b[0], b[1], акцент, 0.05 + 0.14 * з))

    # ──────────────────────── гранёное ядро ────────────────────────
    # Кристалл: вершины на двух кольцах вокруг центра, грани — треугольники
    # «центр — соседние вершины». Получается огранка, а не куча треугольников.
    def кольцо(r, шт, фаза, сплюснутость=0.68):
        из = []
        for i in range(шт):
            a = 2 * math.pi * i / шт + фаза
            из.append(повернуть(ЦХ + r * math.cos(a), ЦУ + r * сплюснутость * math.sin(a), разворот))
        return из

    внутр = кольцо(96, 7, сл.uniform(0, 1))
    средн = кольцо(186, 7, сл.uniform(0, 1) + math.pi / 7)
    внешн = кольцо(268, 7, сл.uniform(0, 1))

    грани = ('crystalA', 'crystalB', 'crystalC')

    for i in range(len(внутр)):
        a = внутр[i]
        b = внутр[(i + 1) % len(внутр)]
        ч.append('<path d="M%.0f,%.0f L%.0f,%.0f L%.0f,%.0f Z" fill="url(#%s)" opacity="%.2f"/>'
                 % (ЦХ, ЦУ, a[0], a[1], b[0], b[1], грани[i % 3], 0.20 + 0.14 * (i % 3)))

    for i in range(len(средн)):
        a = внутр[i]
        b = внутр[(i + 1) % len(внутр)]
        c = средн[i]
        ч.append('<path d="M%.0f,%.0f L%.0f,%.0f L%.0f,%.0f Z" fill="url(#%s)" opacity="%.2f"/>'
                 % (a[0], a[1], b[0], b[1], c[0], c[1], грани[(i + 1) % 3], 0.13 + 0.10 * (i % 3)))
        ч.append('<path d="M%.0f,%.0f L%.0f,%.0f L%.0f,%.0f Z" fill="url(#%s)" opacity="%.2f"/>'
                 % (b[0], b[1], c[0], c[1], средн[(i + 1) % len(средн)][0], средн[(i + 1) % len(средн)][1],
                    грани[(i + 2) % 3], 0.09 + 0.08 * (i % 3)))

    for i in range(len(внешн)):
        c = средн[i]
        d = внешн[i]
        e = средн[(i + 1) % len(средн)]
        ч.append('<path d="M%.0f,%.0f L%.0f,%.0f L%.0f,%.0f Z" fill="url(#%s)" opacity="%.2f"/>'
                 % (c[0], c[1], d[0], d[1], e[0], e[1], грани[i % 3], 0.05 + 0.06 * (i % 2)))

    # Рёбра огранки — тонким контуром, чтобы кристалл читался чётко.
    for набор, оп in ((внутр, 0.30), (средн, 0.20), (внешн, 0.11)):
        for i in range(len(набор)):
            a = набор[i]
            b = набор[(i + 1) % len(набор)]
            ч.append('<line x1="%.0f" y1="%.0f" x2="%.0f" y2="%.0f" stroke="%s" '
                     'stroke-width="1.1" opacity="%.2f"/>' % (a[0], a[1], b[0], b[1], основной, оп))
    for i in range(len(внутр)):
        ч.append('<line x1="%.0f" y1="%.0f" x2="%.0f" y2="%.0f" stroke="%s" '
                 'stroke-width="1" opacity=".22"/>' % (ЦХ, ЦУ, внутр[i][0], внутр[i][1], основной))
        ч.append('<line x1="%.0f" y1="%.0f" x2="%.0f" y2="%.0f" stroke="%s" '
                 'stroke-width=".9" opacity=".15"/>' % (внутр[i][0], внутр[i][1], средн[i][0], средн[i][1], основной))

    # ── Растворение к краям: последним слоем ──
    ч.append('<rect width="%d" height="%d" fill="url(#fade)"/>' % (Ш, В))

    пояснение = (
        '  %s — фон темы «%s».\n\n'
        '  Композиция одна на все темы и читается как знак продукта:\n'
        '    ядро (Core) — гранёный кристалл в середине;\n'
        '    связи (Nexum) — линии от ядра к внешним узлам;\n'
        '    соты — модульность системы;\n'
        '    орбиты — каркас композиции.\n'
        '  Меняются палитра и разворот (%d°).\n\n'
        '  Светящихся узлов нет намеренно: блики читались как засветка от\n'
        '  вспышки и спорили с текстом карточек.\n\n'
        '  Края уходят в ровный цвет фона — слой повторяется, и только так\n'
        '  стык не виден.\n\n'
        '  Файл СОБРАН генератором (scripts/art/theme-backgrounds.py, зерно %d).\n'
        '  Править руками бессмысленно: следующий прогон перезапишет.'
        % (слаг, имя, разворот, зерно)
    )

    svg = ('<?xml version="1.0" encoding="UTF-8"?>\n'
           '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">\n'
           '<!--\n%s\n-->\n%s\n</svg>\n' % (Ш, В, Ш, В, пояснение, '\n'.join(ч)))

    данные = svg.encode('utf-8')
    open(os.path.join(ВЫХОД, слаг + '.svg'), 'wb').write(данные)
    return len(данные)


if __name__ == '__main__':
    for слаг, фон, осн, акц, тём, зерно, разворот, имя in ТЕМЫ:
        n = нарисовать(слаг, фон, осн, акц, тём, зерно, разворот, имя)
        print('%-10s %-10s %6.1f KB' % (слаг, имя, n / 1024))
