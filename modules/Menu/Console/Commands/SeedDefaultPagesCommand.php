    /**
     * Создаёт демо-страницы. Идемпотентно: страница переиспользуется по slug.
     * $reset=true — перезаписывает контент и SEO-поля дефолтных страниц
     * (правки владельца в других страницах не трогаются никогда).
     */
    public static function seed(bool $reset = false): void
    {
        DB::transaction(function () use ($reset) {
            foreach (self::definitions() as $def) {
                $attributes = [
                    'title'            => $def['title'],
                    'content'          => $def['content'],
                    'meta_title'       => $def['meta_title'],
                    'meta_description' => $def['meta_description'],
                    'meta_keywords'    => $def['meta_keywords'],
                    'published'        => true,
                    // Показываем на главной: сразу после установки видно, что раздел
                    // «Страницы» работает и как выглядит вывод страниц на главной.
                    // Порядок задаётся homepage_order.
                    'show_on_homepage' => true,
                    'homepage_order'   => $def['homepage_order'],
                ];

                $page = Page::where('slug', $def['slug'])->first();

                if (! $page) {
                    Page::create($attributes + ['slug' => $def['slug']]);
                    continue;
                }

                if ($reset) {
                    $page->update($attributes);
                }
            }
        });
    }

    public function handle(): int
    {
        $reset = (bool) $this->option('reset');
        self::seed($reset);

        $slugs = collect(self::definitions())->pluck('slug')->implode(', ');
        $this->info(($reset ? 'Демо-страницы перезаписаны' : 'Демо-страницы проверены/созданы')
            . " ({$slugs}).");

        return self::SUCCESS;
    }
