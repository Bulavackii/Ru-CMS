<?php

namespace Modules\Payments\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\Log;
use Modules\Payments\Models\Order;

/**
 * Отмена заказов, за которые не заплатили в срок.
 *
 * ЗАЧЕМ. Товар списывается со склада в момент оформления заказа, а не в
 * момент оплаты. Покупатель ушёл с платёжной страницы и не вернулся — товар
 * так и числится проданным, и следующий покупатель видит «нет в наличии» у
 * позиции, которая на самом деле лежит на складе. Раньше вернуть её можно
 * было только руками: найти заказ в панели и удалить.
 *
 * ⚠️ ТОЛЬКО ОНЛАЙНОВАЯ ОПЛАТА. Наличные и банковский счёт законно ждут
 * днями — «в ожидании» у них означает «ждём покупателя», а не «ждём
 * платёжную систему». Отменять их по таймеру нельзя, поэтому офлайновые
 * способы исключены запросом, а не проверкой внутри цикла: так они не
 * попадают в выборку вовсе.
 *
 * ⚠️ Статус берём РОВНО `pending` — его ставит оформление в корзине.
 * Заказы, заведённые в панели вручную, получают статус `new` и под
 * таймер не подпадают: их создаёт владелец, договорившись с покупателем,
 * и закрывать их через десять минут было бы дико.
 */
class CancelUnpaidOrdersCommand extends Command
{
    protected $signature = 'orders:cancel-unpaid
                            {--dry-run : Показать, что было бы отменено, ничего не меняя}';

    protected $description = 'Отменяет неоплаченные заказы и возвращает товар в продажу';

    /** Причина отмены — она же ключ пояснения в письме покупателю. */
    public const REASON = 'unpaid_timeout';

    public function handle(): int
    {
        $минут = (int) config('payments.unpaid_timeout', 10);

        if ($минут <= 0) {
            $this->info('Отмена по сроку выключена (payments.unpaid_timeout).');

            return self::SUCCESS;
        }

        $просроченные = self::просроченные($минут);

        if ($просроченные->isEmpty()) {
            $this->info('Просроченных заказов нет.');

            return self::SUCCESS;
        }

        $сухой = (bool) $this->option('dry-run');
        $отменено = 0;

        foreach ($просроченные as $order) {
            if ($сухой) {
                $this->line(sprintf('#%d от %s — отменить', $order->id,
                    $order->created_at?->format('d.m.Y H:i')));
                continue;
            }

            self::отменить($order);
            $отменено++;
        }

        $this->info($сухой
            ? sprintf('Под отмену подходит заказов: %d', $просроченные->count())
            : sprintf('Отменено заказов: %d, товар возвращён в продажу.', $отменено));

        return self::SUCCESS;
    }

    /**
     * Заказы, за которые не заплатили в срок.
     *
     * Вынесено отдельным методом, чтобы тем же запросом пользовались и
     * команда, и тесты, и всё, что понадобится потом: условие здесь
     * несущее, и вторая его копия рано или поздно разойдётся с первой.
     */
    public static function просроченные(?int $минут = null)
    {
        $минут ??= (int) config('payments.unpaid_timeout', 10);

        return Order::query()
            ->with('items')
            ->where('status', 'pending')
            ->whereNull('stock_returned_at')
            ->where('created_at', '<', now()->subMinutes($минут))
            // Офлайновые способы ждут сколько нужно. whereHas, а не проверка
            // в цикле: заказ без способа оплаты (данные битые) тоже не должен
            // попасть под отмену — пусть им займётся человек.
            ->whereHas('paymentMethod', fn ($q) => $q->where('type', '!=', 'offline'))
            ->get();
    }

    /**
     * Отменить один заказ и вернуть его товар.
     *
     * ⚠️ Порядок несущий: сперва причина и статус, потом возврат остатка.
     * Смена статуса поднимает событие OrderStatusChanged, а его слушатель
     * шлёт письмо покупателю — причина к этому моменту обязана быть уже
     * в записи, иначе письмо напишет просто «Отменён», без объяснения.
     */
    public static function отменить(Order $order): void
    {
        try {
            $order->forceFill([
                'cancel_reason' => self::REASON,
                'status'        => 'cancelled',
            ])->save();

            $order->returnStockOnce();
        } catch (\Throwable $e) {
            // Один битый заказ не должен останавливать разбор остальных:
            // команда идёт по расписанию, и молчаливая остановка на первом
            // же сбое означала бы, что склад не возвращается вообще.
            Log::error('Не удалось отменить неоплаченный заказ', [
                'order_id' => $order->id,
                'error'    => $e->getMessage(),
            ]);
        }
    }
}
