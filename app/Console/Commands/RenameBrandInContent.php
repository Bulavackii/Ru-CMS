<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Modules\Menu\Models\Page;
use Modules\News\Models\News;

/**
 * Переименование бренда в СОДЕРЖИМОМ сайта.
 *
 * Ребрендинг в коде и шаблонах — это одно, а материалы и страницы лежат в базе:
 * их правил владелец, и заменять их кодом при развёртывании нельзя. На чистой
 * установке содержимое сразу приходит с новым именем (сидеры обновлены), а вот
 * на УЖЕ работающем сайте остаётся старое — в заголовках, тексте, мета-полях и
 * даже в слаге.
 *
 * По умолчанию команда только показывает, что изменится. Правит с `--force`.
 *
 * ⚠️ Правки идут ЧЕРЕЗ МОДЕЛЬ, а не запросом построителя. На событиях модели
 * держатся синхронизация SEO-записей и сброс кеша содержимого: массовый
 * `update()` их не поднимает, и на сайте ещё пять минут висело бы старое имя
 * (этот же урок уже стоил проекту мёртвых SEO-записей).
 *
 * ⚠️ При смене слага заводится перенаправление 301 со старого адреса. Иначе
 * ссылка, которую кто-то уже сохранил или которую проиндексировал поисковик,
 * начнёт вести в 404.
 */
class RenameBrandInContent extends Command
{
    protected $signature = 'brand:rename-content
                            {--force : Действительно править (по умолчанию — только показать)}
                            {--to=Nexum Core : Новое название}
                            {--slug=nexum-core : Новое написание для слагов и адресов}';

    protected $description = 'Заменить старое название проекта в материалах и страницах';

    /**
     * Что на что менять. Порядок важен: длинные варианты первыми, иначе
     * короткий «RuShop» съест начало «RuShop CMS».
     */
    private function замены(): array
    {
        $имя = (string) $this->option('to');
        $слаг = (string) $this->option('slug');

        return [
            'RuShop CMS' => $имя,
            'RuShop'     => $имя,
            'RU CMS'     => $имя,
            'RU-CMS'     => $имя,
            'Ru-CMS'     => $имя,
            'ru-cms'     => $слаг,
            'rucms'      => $слаг,
        ];
    }

    /** Поля, в которых ищем. Слаг обрабатывается отдельно — он адрес. */
    private const ПОЛЯ = ['title', 'content', 'meta_title', 'meta_description', 'meta_keywords'];

    public function handle(): int
    {
        $правим = (bool) $this->option('force');
        $замены = $this->замены();
        $всего = 0;

        foreach ([News::class, Page::class] as $класс) {
            $всего += $this->пройти($класс, $замены, $правим);
        }

        $всего += $this->слайды($замены, $правим);
        $всего += $this->seoЗаписи($замены, $правим);
        $всего += $this->файлы($замены, $правим);

        if ($всего === 0) {
            $this->info('Старого названия в содержимом нет.');

            return self::SUCCESS;
        }

        if (! $правим) {
            $this->line('');
            $this->comment("Это только показ. Чтобы применить: php artisan brand:rename-content --force");
        } else {
            $this->line('');
            $this->info("Записей изменено: {$всего}");
        }

        return self::SUCCESS;
    }

    private function пройти(string $класс, array $замены, bool $правим): int
    {
        $изменено = 0;
        $таблица = (new $класс)->getTable();

        foreach ($класс::query()->get() as $запись) {
            $правки = [];

            foreach (self::ПОЛЯ as $поле) {
                if (! array_key_exists($поле, $запись->getAttributes())) {
                    continue;   // у страниц нет части мета-полей материала
                }

                $было = (string) ($запись->{$поле} ?? '');

                if ($было === '') {
                    continue;
                }

                $стало = str_replace(array_keys($замены), array_values($замены), $было);

                if ($стало !== $было) {
                    $правки[$поле] = $стало;
                }
            }

            // Слаг — это адрес, поэтому отдельно и с перенаправлением
            $старыйСлаг = (string) ($запись->slug ?? '');
            $новыйСлаг = str_replace(array_keys($замены), array_values($замены), $старыйСлаг);
            $слагМеняется = $новыйСлаг !== $старыйСлаг;

            if ($правки === [] && ! $слагМеняется) {
                continue;
            }

            $изменено++;

            $this->line(sprintf(
                '%s #%d %s%s',
                $таблица,
                $запись->id,
                $старыйСлаг,
                $слагМеняется ? " → {$новыйСлаг}" : ''
            ));

            foreach ($правки as $поле => $_) {
                $this->line("    {$поле}");
            }

            if (! $правим) {
                continue;
            }

            if ($слагМеняется) {
                $this->завестиПеренаправление($таблица, $старыйСлаг, $новыйСлаг);
                $правки['slug'] = $новыйСлаг;
            }

            // Через модель: на событиях держатся SEO и сброс кеша.
            $запись->fill($правки)->save();
        }

        return $изменено;
    }

    /** Подписи слайдов: они видны на главной крупнее всего остального. */
    private function слайды(array $замены, bool $правим): int
    {
        if (! class_exists(\Modules\Slideshow\Models\SlideshowItem::class)) {
            return 0;
        }

        return $this->простыеПоля(
            \Modules\Slideshow\Models\SlideshowItem::class,
            ['caption', 'alt_text', 'title', 'description'],
            $замены,
            $правим
        );
    }

    /**
     * SEO-записи: заголовок, H1 и описание для поисковика.
     *
     * ⚠️ `slug` и `canonical` здесь — АДРЕСА, и они должны следовать за слагом
     * материала. Правятся тем же набором замен, что и слаг: иначе в карте сайта
     * останется адрес, которого больше нет.
     */
    private function seoЗаписи(array $замены, bool $правим): int
    {
        if (! class_exists(\Modules\Seo\Models\SeoPage::class)) {
            return 0;
        }

        return $this->простыеПоля(
            \Modules\Seo\Models\SeoPage::class,
            ['title', 'h1', 'description', 'canonical', 'slug'],
            $замены,
            $правим
        );
    }

    /**
     * Медиатека: название, подпись и САМ ФАЙЛ.
     *
     * ⚠️ Путь в базе связан с файлом на диске. Переименовать запись, не тронув
     * файл, значит получить битую картинку — поэтому файл переносится, и только
     * при успехе правится путь.
     */
    private function файлы(array $замены, bool $правим): int
    {
        if (! class_exists(\Modules\Files\Models\File::class)) {
            return 0;
        }

        $изменено = 0;

        foreach (\Modules\Files\Models\File::query()->get() as $файл) {
            $правки = [];

            foreach (['name', 'alt_text', 'original_name', 'description'] as $поле) {
                if (! array_key_exists($поле, $файл->getAttributes())) {
                    continue;
                }

                $было = (string) ($файл->{$поле} ?? '');
                $стало = str_replace(array_keys($замены), array_values($замены), $было);

                if ($было !== '' && $стало !== $было) {
                    $правки[$поле] = $стало;
                }
            }

            $старыйПуть = (string) ($файл->path ?? '');
            $новыйПуть = str_replace(array_keys($замены), array_values($замены), $старыйПуть);
            $путьМеняется = $новыйПуть !== $старыйПуть;

            if ($правки === [] && ! $путьМеняется) {
                continue;
            }

            $изменено++;
            $this->line('files #' . $файл->id . ' ' . $старыйПуть . ($путьМеняется ? " → {$новыйПуть}" : ''));

            foreach (array_keys($правки) as $поле) {
                $this->line("    {$поле}");
            }

            if (! $правим) {
                continue;
            }

            if ($путьМеняется) {
                $диск = \Illuminate\Support\Facades\Storage::disk('public');

                if ($диск->exists($старыйПуть) && ! $диск->exists($новыйПуть)) {
                    $диск->move($старыйПуть, $новыйПуть);
                    $правки['path'] = $новыйПуть;
                    $this->line('    файл перенесён на диске');
                } elseif ($диск->exists($новыйПуть)) {
                    $правки['path'] = $новыйПуть;   // уже перенесён ранее
                } else {
                    // Файла нет — путь НЕ меняем, иначе запись начнёт ссылаться
                    // в пустоту и битую картинку станет труднее объяснить.
                    $this->warn('    файла нет на диске — путь оставлен как был');
                }
            }

            $файл->fill($правки)->save();
        }

        return $изменено;
    }

    /**
     * Общий проход по модели с набором текстовых полей.
     *
     * Через модель, а не запросом: на событиях держатся сброс кеша и синхронизация.
     */
    private function простыеПоля(string $класс, array $поля, array $замены, bool $правим): int
    {
        $изменено = 0;
        $таблица = (new $класс)->getTable();

        foreach ($класс::query()->get() as $запись) {
            $правки = [];

            foreach ($поля as $поле) {
                if (! array_key_exists($поле, $запись->getAttributes())) {
                    continue;
                }

                $было = (string) ($запись->{$поле} ?? '');

                if ($было === '') {
                    continue;
                }

                $стало = str_replace(array_keys($замены), array_values($замены), $было);

                if ($стало !== $было) {
                    $правки[$поле] = $стало;
                }
            }

            if ($правки === []) {
                continue;
            }

            $изменено++;
            $this->line($таблица . ' #' . $запись->id . ': ' . implode(', ', array_keys($правки)));

            if (! $правим) {
                continue;
            }

            // ⚠️ У SeoPage `slug` НЕ в fillable (защита от массового
            // затирания), поэтому ставится напрямую.
            if (isset($правки['slug'])) {
                // 🔴 Запись с новым адресом может УЖЕ существовать.
                //
                // Так и вышло: когда у материала переименовали слаг, слушатель
                // синхронизации SEO тут же завёл запись под новый адрес. Старая
                // осталась описывать адрес, которого больше нет, и попытка
                // переименовать её падала на уникальности слага.
                //
                // Такую старую запись убираем, а не переименовываем: она дубль.
                // Удаление мягкое (`SoftDeletes`), то есть восстановимое.
                $занято = $класс::where('slug', $правки['slug'])
                    ->whereKeyNot($запись->getKey())
                    ->exists();

                if ($занято) {
                    $this->warn('    адрес уже описан другой записью — эта удалена как дубль');
                    $запись->delete();

                    continue;
                }

                $запись->slug = $правки['slug'];
                unset($правки['slug']);
            }

            try {
                $запись->fill($правки)->save();
            } catch (\Throwable $e) {
                // Одна запись не должна ронять весь проход: остальные правки
                // полезны и без неё, а причина видна сразу.
                $this->warn('    не сохранено: ' . mb_substr($e->getMessage(), 0, 100));
            }
        }

        return $изменено;
    }

    /**
     * Перенаправление 301 со старого адреса на новый.
     *
     * ⚠️ Адрес материала и страницы строится по-разному (`/news/…` против
     * `/page/…`), поэтому префикс берётся по таблице, а не угадывается.
     */
    private function завестиПеренаправление(string $таблица, string $старый, string $новый): void
    {
        if (! class_exists(\Modules\Seo\Models\RedirectRule::class)) {
            $this->warn('    модуль SEO недоступен — перенаправление не заведено');

            return;
        }

        $префикс = $таблица === 'news' ? '/news/' : '/page/';

        \Modules\Seo\Models\RedirectRule::firstOrCreate(
            ['from' => $префикс . $старый],
            ['to' => $префикс . $новый, 'code' => '301', 'is_regex' => false, 'priority' => 100],
        );

        $this->line("    перенаправление {$префикс}{$старый} → {$префикс}{$новый}");
    }
}
