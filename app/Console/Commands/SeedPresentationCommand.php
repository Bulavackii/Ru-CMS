/**
 * Витрина продукта: главная страница после установки должна ПРОДАВАТЬ.
 *
 * До этого свежая установка показывала вперемешку демо-магазин, клинику,
 * игровой раздел и учебные уроки — набор, который демонстрирует шаблоны, но
 * ничего не говорит о продукте. Плюс на главную выводились ВСЕ страницы,
 * включая пользовательское соглашение, политику конфиденциальности и карту
 * сайта: юридический подвал посреди витрины.
 *
 * Команда собирает связный рассказ: чем система отличается, чем она лучше
 * WordPress и Битрикса, во что обходится владение и как начать.
 *
 * ⚠️ Лишнее НЕ УДАЛЯЕТСЯ. Демо-материалы остаются опубликованными и доступными
 * по своим адресам — они снимаются только с ГЛАВНОЙ (`show_on_homepage`).
 * Шаблоны никто не трогает: их можно посмотреть в разделе «Материалы» и
 * вернуть на главную одной галочкой.
 */
class SeedPresentationCommand extends Command
{
    protected $signature = 'presentation:seed
                            {--reset : Перезаписать тексты страниц витрины}';

    protected $description = 'Собрать продающую главную страницу: сравнение, стоимость владения, как начать';

    /**
     * Шаблоны материалов, которые остаются на главной.
     *
     * «Журнал» — статьи, которые продают; «Отзывы» — доверие; «Релизы» —
     * доказательство, что продукт живой и развивается. Всё остальное
     * (магазин, клиника, игры, уроки) с главной снимается: оно показывает
     * возможности шаблонов, а не продукт.
     */
    private const ШАБЛОНЫ_НА_ГЛАВНОЙ = ['magazine', 'reviews', 'release'];

    /**
     * Страницы, которые остаются на главной, в порядке рассказа.
     *
     * Порядок — это и есть сценарий продажи: сперва боль и обещание, потом
     * доказательство сравнением, потом деньги, потом возражения, и только в
     * конце — что делать дальше.
     */
    private const ПОРЯДОК_ГЛАВНОЙ = [
        'pochemu-nexum-core' => 1,
        'sravnenie'          => 2,
        'vozmozhnosti'       => 3,
        'stoimost-vladeniya' => 4,
        'chastye-voprosy'    => 5,
        'kak-nachat'         => 6,
    ];

    /**
     * Статический вход для мастера установки.
     *
     * Мастер зовёт сидеры именно так, а не по имени команды: команды модулей
     * регистрируются только у активных модулей, и вызов по имени однажды уже
     * оказывался несуществующим.
     *
     * @return int сколько страниц витрины заведено
     */
    public static function seed(bool $reset = false): int
    {
        $экземпляр = new self();

        return DB::transaction(function () use ($экземпляр, $reset) {
            $заведено = $экземпляр->страницыВитрины($reset);
            $экземпляр->разложитьГлавную();
            $экземпляр->материалыЖурнала($reset);

            return $заведено;
        });
    }

    public function handle(): int
    {
        $заведено = self::seed((bool) $this->option('reset'));

        $this->info($заведено
            ? "Страниц витрины заведено: {$заведено}"
            : 'Страницы витрины уже на месте');

        $this->info('Главная собрана: страницы — по сценарию, демо-разделы сняты с витрины.');
        $this->line('Ничего не удалено: снятое доступно по своим адресам и возвращается галочкой.');

        return self::SUCCESS;
    }

    /** Заводит страницы витрины. Идемпотентно по слагу. */
    private function страницыВитрины(bool $reset): int
    {
        $заведено = 0;

        foreach ($this->страницы() as $опр) {
            $поля = [
                'title'            => $опр['title'],
                'content'          => $опр['content'],
                'meta_title'       => $опр['meta_title'],
                'meta_description' => $опр['meta_description'],
                'published'        => true,
                'show_on_homepage' => true,
                'homepage_order'   => self::ПОРЯДОК_ГЛАВНОЙ[$опр['slug']] ?? 99,
            ];

            $страница = Page::where('slug', $опр['slug'])->first();

            if (! $страница) {
                // Через модель: на событиях держатся SEO-запись и сброс кеша.
                $новая = new Page($поля);
                $новая->slug = $опр['slug'];
                $новая->save();
                $заведено++;

                continue;
            }

            if ($reset) {
                $страница->update($поля);
            }
        }

        return $заведено;
    }

    /**
     * Раскладывает главную: витрина сверху, служебное — прочь.
     *
     * ⚠️ Через модель, а не `update()` построителем: на событиях держится
     * сброс кеша главной. Массовым запросом страница пропала бы с витрины
     * только через час.
     */
    private function разложитьГлавную(): void
    {
        foreach (Page::all() as $страница) {
            $наГлавной = array_key_exists($страница->slug, self::ПОРЯДОК_ГЛАВНОЙ);

            $надо = ['show_on_homepage' => $наГлавной];

            // ⚠️ Порядок задаём ТОЛЬКО тем, кто на витрине. У скрытых он не
            // значит ничего, а обнулить его нельзя: `pages.homepage_order`
            // объявлен NOT NULL, и запись падала с «значение NULL в столбце».
            if ($наГлавной) {
                $надо['homepage_order'] = self::ПОРЯДОК_ГЛАВНОЙ[$страница->slug];
            }

            $совпадает = (bool) $страница->show_on_homepage === $надо['show_on_homepage']
                && (! $наГлавной || (int) $страница->homepage_order === $надо['homepage_order']);

            if ($совпадает) {
                continue;
            }

            $страница->update($надо);
        }

        // Материалы: на витрине остаются только те шаблоны, что продают.
        foreach (News::all() as $материал) {
            $надо = in_array($материал->template, self::ШАБЛОНЫ_НА_ГЛАВНОЙ, true);

            if ((bool) $материал->show_on_homepage === $надо) {
                continue;
            }

            $материал->update(['show_on_homepage' => $надо]);
        }
    }

    /** Статьи журнала, которые продают. Идемпотентно по слагу. */
    private function материалыЖурнала(bool $reset): void
    {
        foreach ($this->статьи() as $опр) {
            $поля = [
                'title'            => $опр['title'],
                'content'          => $опр['content'],
                'template'         => 'magazine',
                'published'        => true,
                'show_on_homepage' => true,
                'meta_title'       => $опр['meta_title'] ?? $опр['title'],
                'meta_description' => $опр['meta_description'] ?? null,
            ];

            $материал = News::where('slug', $опр['slug'])->first();

            if (! $материал) {
                $новый = new News($поля);
                $новый->slug = $опр['slug'];
                $новый->save();

                continue;
            }

            if ($reset) {
                $материал->update($поля);
            }
        }
    }

